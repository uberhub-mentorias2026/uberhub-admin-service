    CREATE TABLE IF NOT EXISTS ADMIN_USUARIOS (
        ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
        USUARIO_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do Auth service',
        NOME VARCHAR(160) NOT NULL,
        EMAIL VARCHAR(254) NOT NULL,
        PERFIL VARCHAR(30) NOT NULL COMMENT 'MENTOR, MENTORADO ou ADMIN',
        STATUS_ACESSO VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
        -- NOVOS CAMPOS
        APROVADO_PARA_MENTORIA BOOLEAN NOT NULL DEFAULT FALSE,
        DATA_APROVACAO DATETIME(3) NULL,
        APROVADO_POR_ID BIGINT UNSIGNED NULL,
        --
        MOTIVO_SUSPENSAO VARCHAR(500) NULL,
        ORIGEM_ATUALIZADO_EM DATETIME(3) NULL,
        CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
        ATUALIZADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
        PRIMARY KEY (ID),

        UNIQUE KEY UQ_ADMIN_USUARIOS_UUID (USUARIO_UUID),
        UNIQUE KEY UQ_ADMIN_USUARIOS_EMAIL (EMAIL),

        KEY IX_ADMIN_USUARIOS_STATUS_PERFIL (STATUS_ACESSO, PERFIL),
        KEY IX_ADMIN_USUARIOS_APROVADOR (APROVADO_POR_ID),

        CONSTRAINT FK_ADMIN_USUARIOS_APROVADOR
            FOREIGN KEY (APROVADO_POR_ID)
            REFERENCES ADMIN_USUARIOS(ID)
            ON UPDATE CASCADE
            ON DELETE SET NULL,

        CONSTRAINT CK_ADMIN_USUARIOS_STATUS
            CHECK (STATUS_ACESSO IN ('ATIVO','SUSPENSO','INATIVO')),

        CONSTRAINT CK_ADMIN_USUARIOS_PERFIL
            CHECK (PERFIL IN ('MENTOR','MENTORADO','ADMIN')),

        CONSTRAINT CK_ADMIN_USUARIOS_APROVACAO
            CHECK ((
                APROVADO_PARA_MENTORIA = FALSE
                AND DATA_APROVACAO IS NULL
                AND APROVADO_POR_ID IS NULL
            ) OR (
                APROVADO_PARA_MENTORIA = TRUE
                AND DATA_APROVACAO IS NOT NULL
                AND APROVADO_POR_ID IS NOT NULL
            )
        )
    ) ENGINE=INNODB COMMENT='Projeção local de usuários do Auth service';




